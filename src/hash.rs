//! Self-contained SHA-256 and CRC-32 implementations.
//!
//! SeanPak's dependency rule (windows-sys only) rules out crypto/archive
//! crates, but the release pipeline needs SHA-256 (for `SHA256SUMS.txt`
//! and the JSON build report) and CRC-32 (for the portable ZIP). Both
//! algorithms are small, public-domain constructions; these are direct
//! implementations verified against published test vectors in the tests
//! below.

/// Computes the SHA-256 digest of `data` and returns it as lowercase hex.
pub fn sha256_hex(data: &[u8]) -> String {
    let digest = Sha256::digest(data);
    let mut out = String::with_capacity(64);
    for byte in digest {
        out.push_str(&format!("{byte:02x}"));
    }
    out
}

/// Computes the SHA-256 digest of a file's contents, streaming it in
/// chunks so large payloads are never held in memory.
pub fn sha256_file_hex(path: &std::path::Path) -> std::io::Result<String> {
    use std::io::Read;
    let mut file = std::fs::File::open(path)?;
    let mut hasher = Sha256::new();
    let mut buffer = [0u8; 65536];
    loop {
        let n = file.read(&mut buffer)?;
        if n == 0 {
            break;
        }
        hasher.update(&buffer[..n]);
    }
    let digest = hasher.finish();
    let mut out = String::with_capacity(64);
    for byte in digest {
        out.push_str(&format!("{byte:02x}"));
    }
    Ok(out)
}

struct Sha256 {
    state: [u32; 8],
    buffer: [u8; 64],
    buffer_len: usize,
    total_len: u64,
}

