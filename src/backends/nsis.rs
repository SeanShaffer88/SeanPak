use super::{BuildConfig, InstallerBackend, PrivilegeLevel, TargetInstallDir, ToolStatus};
use std::fs;
use std::path::PathBuf;
use std::process::Command;

pub struct NsisBackend;

impl NsisBackend {
    pub fn new() -> Self {
        Self
    }

    /// Locate the NSIS compiler executable `makensis.exe`
    pub fn find_makensis() -> Option<PathBuf> {
        // 1. Check if makensis is in PATH
        if let Ok(output) = Command::new("where").arg("makensis.exe").output() {
            if output.status.success() {
                if let Ok(paths) = String::from_utf8(output.stdout) {
                    if let Some(first) = paths.lines().next() {
                        let path = PathBuf::from(first.trim());
                        if path.is_file() {
                            return Some(path);
                        }
                    }
                }
            }
        }

        // 2. Check standard Windows installation directories
        let standard_paths = [
            r"C:\Program Files (x86)\NSIS\makensis.exe",
            r"C:\Program Files\NSIS\makensis.exe",
            r"C:\Tools\NSIS\makensis.exe",
        ];

        for path in standard_paths {
            let p = PathBuf::from(path);
            if p.is_file() {
                return Some(p);
            }
        }

        None
    }
}

impl Default for NsisBackend {
    fn default() -> Self {
        Self::new()
    }
}

impl InstallerBackend for NsisBackend {
    fn name(&self) -> &'static str {
        "NSIS (Nullsoft Scriptable Install System)"
    }

    fn description(&self) -> &'static str {
        "Lightweight, highly flexible scriptable installer system utilizing Modern UI 2 (MUI2) and LZMA/BZIP2 compression."
    }

    fn script_extension(&self) -> &'static str {
        "nsi"
    }

    fn check_tool_installed(&self) -> ToolStatus {
        match Self::find_makensis() {
            Some(path) => ToolStatus::Ready(path),
            None => ToolStatus::NotFound {
                hint: "makensis.exe not found. Install NSIS 3.x from https://nsis.sourceforge.io/Download or add to PATH.".to_string(),
            },
        }
    }

    fn generate_script(&self, config: &BuildConfig) -> std::io::Result<String> {
        let install_dir_macro = match &config.target_dir {
            TargetInstallDir::ProgramFiles64 => "$PROGRAMFILES64\\",
            TargetInstallDir::LocalAppData => "$LOCALAPPDATA\\",
            TargetInstallDir::Custom(custom) => custom.as_str(),
        };

        let request_level = match config.privileges {
            PrivilegeLevel::RequireAdministrator => "admin",
            PrivilegeLevel::AsInvoker => "user",
        };

        let source_files = config
            .source_dir
            .canonicalize()
            .unwrap_or_else(|_| config.source_dir.clone())
            .to_string_lossy()
            .replace('/', "\\");

        let icon_directives = if let Some(ref icon) = config.custom_icon_path {
            let icon_str = icon.to_string_lossy().replace('/', "\\");
            format!(
                "!define MUI_ICON \"{}\"\n!define MUI_UNICON \"{}\"\n",
                icon_str, icon_str
            )
        } else {
            String::new()
        };

        let startup_reg = if config.startup_registry {
            format!(
                "  WriteRegStr HKCU \"Software\\Microsoft\\Windows\\CurrentVersion\\Run\" \"{}\" \"$INSTDIR\\{}\"\n",
                config.app_name, config.primary_exe
            )
        } else {
            String::new()
        };

        let file_assoc_reg = if let Some(ref ext) = config.file_association_ext {
            let clean_ext = ext.trim_start_matches('.');
            format!(
                r#"
  ; Register .{ext} file association
  WriteRegStr HKCR ".{ext}" "" "{app_name}.File"
  WriteRegStr HKCR "{app_name}.File" "" "{app_name} File"
  WriteRegStr HKCR "{app_name}.File\DefaultIcon" "" "$INSTDIR\{primary_exe},0"
  WriteRegStr HKCR "{app_name}.File\shell\open\command" "" '"$INSTDIR\{primary_exe}" "%1"'
"#,
                ext = clean_ext,
                app_name = config.app_name.replace(' ', ""),
                primary_exe = config.primary_exe
            )
        } else {
            String::new()
        };

        let output_file_path = config
            .output_dir
            .join(&config.output_exe_name)
            .to_string_lossy()
            .replace('/', "\\");

        let script = format!(
            r#"; Script generated by SeanPak (High-Throughput Windows Packager)
; NSIS Modern UI 2 (MUI2) Installer Script

Unicode true
SetCompressor /SOLID lzma

; General Definitions
!define PRODUCT_NAME "{app_name}"
!define PRODUCT_VERSION "{version}"
!define PRODUCT_PUBLISHER "{publisher}"
!define PRODUCT_WEB_SITE "{website}"
!define PRODUCT_EXE "{primary_exe}"
!define PRODUCT_UNINST_KEY "Software\Microsoft\Windows\CurrentVersion\Uninstall\${{PRODUCT_NAME}}"

; Include Modern UI 2
!include "MUI2.nsh"
!include "x64.nsh"

; Installer Properties
Name "${{PRODUCT_NAME}} ${{PRODUCT_VERSION}}"
OutFile "{output_file}"
InstallDir "{install_dir_macro}${{PRODUCT_NAME}}"
RequestExecutionLevel {request_level}
{icon_directives}
; Modern UI Pages
!define MUI_ABORTWARNING
!insertmacro MUI_PAGE_WELCOME
!insertmacro MUI_PAGE_DIRECTORY
!insertmacro MUI_PAGE_INSTFILES

!define MUI_FINISHPAGE_RUN "$INSTDIR\${{PRODUCT_EXE}}"
!define MUI_FINISHPAGE_RUN_TEXT "Launch ${{PRODUCT_NAME}}"
!insertmacro MUI_PAGE_FINISH

; Uninstaller Pages
!insertmacro MUI_UNPAGE_CONFIRM
!insertmacro MUI_UNPAGE_INSTFILES
!insertmacro MUI_UNPAGE_FINISH

; Languages
!insertmacro MUI_LANGUAGE "English"

; Installation Section
Section "MainSection" SEC01
  SetOutPath "$INSTDIR"
  SetOverwrite ifnewer
  
  ; Copy payload files recursively
  File /r "{source_files}\*.*"

  ; Shortcuts
{shortcuts_section}

  ; Startup Registry
{startup_reg}
  ; File Association
{file_assoc_reg}
  ; Uninstaller generation
{uninstaller_block}
SectionEnd

; Uninstaller Section
Section "Uninstall"
  ; Remove Registry Keys
  DeleteRegKey HKLM "${{PRODUCT_UNINST_KEY}}"
  DeleteRegValue HKCU "Software\Microsoft\Windows\CurrentVersion\Run" "${{PRODUCT_NAME}}"

  ; Remove Shortcuts
  Delete "$DESKTOP\${{PRODUCT_NAME}}.lnk"
  Delete "$SMPROGRAMS\${{PRODUCT_NAME}}\${{PRODUCT_NAME}}.lnk"
  Delete "$SMPROGRAMS\${{PRODUCT_NAME}}\Uninstall.lnk"
  RMDir "$SMPROGRAMS\${{PRODUCT_NAME}}"

  ; Remove Installed Directory
  RMDir /r "$INSTDIR"

  SetAutoClose true
SectionEnd
"#,
            app_name = config.app_name,
            version = config.version,
            publisher = config.publisher,
            website = config.website,
            primary_exe = config.primary_exe,
            output_file = output_file_path,
            install_dir_macro = install_dir_macro,
            request_level = request_level,
            icon_directives = icon_directives,
            source_files = source_files,
            shortcuts_section = {
                let mut s = String::new();
                if config.start_menu_shortcut {
                    s.push_str("  CreateDirectory \"$SMPROGRAMS\\${PRODUCT_NAME}\"\n");
                    s.push_str("  CreateShortCut \"$SMPROGRAMS\\${PRODUCT_NAME}\\${PRODUCT_NAME}.lnk\" \"$INSTDIR\\${PRODUCT_EXE}\"\n");
                    if config.clean_uninstaller {
                        s.push_str("  CreateShortCut \"$SMPROGRAMS\\${PRODUCT_NAME}\\Uninstall.lnk\" \"$INSTDIR\\uninstall.exe\"\n");
                    }
                }
                if config.desktop_shortcut {
                    s.push_str("  CreateShortCut \"$DESKTOP\\${PRODUCT_NAME}.lnk\" \"$INSTDIR\\${PRODUCT_EXE}\"\n");
                }
                s
            },
            startup_reg = startup_reg,
            file_assoc_reg = file_assoc_reg,
            uninstaller_block = if config.clean_uninstaller {
                r#"
  ; Write uninstaller binary
  WriteUninstaller "$INSTDIR\uninstall.exe"

  ; Register in Windows Add/Remove Programs
  WriteRegStr HKLM "${PRODUCT_UNINST_KEY}" "DisplayName" "${PRODUCT_NAME}"
  WriteRegStr HKLM "${PRODUCT_UNINST_KEY}" "UninstallString" '"$INSTDIR\uninstall.exe"'
  WriteRegStr HKLM "${PRODUCT_UNINST_KEY}" "DisplayIcon" '"$INSTDIR\${PRODUCT_EXE}"'
  WriteRegStr HKLM "${PRODUCT_UNINST_KEY}" "DisplayVersion" "${PRODUCT_VERSION}"
  WriteRegStr HKLM "${PRODUCT_UNINST_KEY}" "Publisher" "${PRODUCT_PUBLISHER}"
  WriteRegStr HKLM "${PRODUCT_UNINST_KEY}" "URLInfoAbout" "${PRODUCT_WEB_SITE}"
"#
                .to_string()
            } else {
                String::new()
            }
        );

        Ok(script)
    }

    fn build(
        &self,
        config: &BuildConfig,
        log_fn: &mut dyn FnMut(&str),
    ) -> std::io::Result<PathBuf> {
        let makensis_path = Self::find_makensis().ok_or_else(|| {
            std::io::Error::new(
                std::io::ErrorKind::NotFound,
                "NSIS Compiler (makensis.exe) was not found on this system.",
            )
        })?;

        log_fn(&format!(
            "Generating NSIS MUI2 script for '{}'...",
            config.app_name
        ));
        let nsi_script = self.generate_script(config)?;

        fs::create_dir_all(&config.output_dir)?;
        let script_path = config
            .output_dir
            .join(format!("{}.nsi", config.app_name.replace(' ', "_")));
        fs::write(&script_path, &nsi_script)?;
        log_fn(&format!("Wrote NSIS script: {}", script_path.display()));

        log_fn(&format!("Invoking compiler: {}", makensis_path.display()));
        let mut child = Command::new(&makensis_path)
            .arg("/V3")
            .arg(&script_path)
            .stdout(std::process::Stdio::piped())
            .stderr(std::process::Stdio::piped())
            .spawn()?;

        if let Some(stdout) = child.stdout.take() {
            use std::io::{BufRead, BufReader};
            let reader = BufReader::new(stdout);
            for line in reader.lines().map_while(Result::ok) {
                log_fn(&line);
            }
        }

        let status = child.wait()?;
        if !status.success() {
            return Err(std::io::Error::other(format!(
                "makensis.exe failed with exit code: {:?}",
                status.code()
            )));
        }

        let output_file = config.output_dir.join(&config.output_exe_name);
        log_fn(&format!(
            "Successfully generated NSIS installer at: {}",
            output_file.display()
        ));
        Ok(output_file)
    }
}

#[cfg(test)]
mod tests {
    use super::*;
    use crate::backends::BuildConfig;

    fn config() -> BuildConfig {
        BuildConfig {
            app_name: "Widget Pro".to_string(),
            version: "3.1.0".to_string(),
            ..Default::default()
        }
    }

    #[test]
    fn script_contains_identity_and_uninstaller() {
        let backend = NsisBackend::new();
        let script = backend.generate_script(&config()).unwrap();
        assert!(script.contains("!define PRODUCT_NAME \"Widget Pro\""));
        assert!(script.contains("!define PRODUCT_VERSION \"3.1.0\""));
        assert!(script.contains("MUI2.nsh"));
        assert!(script.contains("WriteUninstaller"));
        assert!(script.contains("RequestExecutionLevel admin"));
    }

    #[test]
    fn uninstaller_block_omitted_when_disabled() {
        let backend = NsisBackend::new();
        let off = BuildConfig {
            clean_uninstaller: false,
            ..config()
        };
        let script = backend.generate_script(&off).unwrap();
        assert!(!script.contains("WriteUninstaller \"$INSTDIR\\uninstall.exe\""));
    }

    #[test]
    fn local_app_data_target_changes_install_dir() {
        let backend = NsisBackend::new();
        let c = BuildConfig {
            target_dir: TargetInstallDir::LocalAppData,
            ..config()
        };
        let script = backend.generate_script(&c).unwrap();
        assert!(script.contains("$LOCALAPPDATA"));
    }
}
